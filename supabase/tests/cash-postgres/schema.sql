-- Esquema mínimo AISLADO para compilar las migraciones de caja 042-045.
-- Solo CI local efímero; nunca usar en Supabase ni producción.
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT NULLIF(current_setting('request.jwt.claim.sub', true),'')::uuid
$$;
CREATE TABLE public.usuario (
 id integer PRIMARY KEY, empresa_id integer NOT NULL, auth_user_id uuid UNIQUE, activo boolean NOT NULL DEFAULT true
);
CREATE TABLE public.sucursal (id integer PRIMARY KEY, empresa_id integer NOT NULL);
CREATE TABLE public.usuario_sucursal (usuario_id integer NOT NULL, sucursal_id integer NOT NULL, PRIMARY KEY(usuario_id,sucursal_id));
CREATE TABLE public.caja (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sucursal_id integer NOT NULL, usuario_id integer NOT NULL,
 saldo_inicial numeric(12,2) NOT NULL DEFAULT 0, fecha_apertura timestamptz NOT NULL DEFAULT now(),
 fecha_cierre timestamptz, estado varchar(10) NOT NULL DEFAULT 'ABIERTA',
 efectivo_contado numeric(12,2), diferencia numeric(12,2), arqueo jsonb
);
CREATE UNIQUE INDEX uq_caja_abierta_sucursal_usuario ON public.caja(sucursal_id,usuario_id) WHERE estado='ABIERTA';
CREATE TABLE public.comprobante (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id integer NOT NULL, sucursal_id integer NOT NULL,
 caja_id integer, usuario_id integer NOT NULL, total numeric(12,2) NOT NULL DEFAULT 0,
 metodo_pago varchar(10) NOT NULL, estado varchar(10) NOT NULL DEFAULT 'PAGADA'
);
CREATE TABLE public.comprobante_pago (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, comprobante_id integer NOT NULL,
 metodo_pago varchar(10) NOT NULL, monto numeric(12,2) NOT NULL
);
CREATE TABLE public.caja_movimiento (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, caja_id integer NOT NULL, usuario_id integer NOT NULL,
 tipo varchar(10) NOT NULL, metodo_pago varchar(10) NOT NULL, monto numeric(12,2) NOT NULL,
 motivo text, created_at timestamptz NOT NULL DEFAULT now(), comprobante_id integer,
 compra_id bigint, cobro_cliente_id bigint, devolucion_venta_id bigint
);
CREATE TABLE public.devolucion_venta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, caja_id integer NOT NULL,
 empresa_id integer NOT NULL, estado varchar(20) NOT NULL, total_devolucion numeric(12,2) NOT NULL DEFAULT 0
);
CREATE TABLE public.devolucion_venta_pago (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, devolucion_id bigint NOT NULL,
 empresa_id integer NOT NULL, sucursal_id integer NOT NULL, metodo_pago varchar(10) NOT NULL,
 monto numeric(12,2) NOT NULL, referencia text, created_at timestamptz NOT NULL DEFAULT now()
);
